/**
 * Production SVG → PNG renderer wrapper for Sovereign Decks.
 *
 * This wraps the existing @resvg/resvg-js implementation used in production
 * (Trigger.dev jobs) to match the competition interface.
 *
 * Note: The production system has two rendering paths:
 * - Node.js path (jobs/): Uses @resvg/resvg-js (this file)
 * - Worker path (server/): Uses @cf-wasm/resvg/workerd (Cloudflare Workers)
 *
 * This implementation uses the Node.js path for benchmarking.
 */

import { Resvg } from '@resvg/resvg-js'

export interface RenderOptions {
  width: number
  height: number
  fonts?: FontConfig[]
}

export interface FontConfig {
  name: string
  data: ArrayBuffer
  weight?: number
  style?: 'normal' | 'italic'
}

export interface RenderResult {
  png: Uint8Array
  renderTime: number // ms
  memoryUsed?: number // optional: bytes used
}

/**
 * Render SVG to PNG using resvg-js.
 *
 * This is the same logic used in production:
 * - packages/ui/src/render.ts (renderCard function)
 * - jobs/src/render-card.ts
 *
 * The SVG is pre-generated by Satori, so fonts are already embedded as paths.
 * The resvg step just rasterizes the SVG to PNG.
 */
export async function renderSvgToPng(
  svg: string,
  options: RenderOptions
): Promise<RenderResult> {
  const start = performance.now()

  // Initialize resvg with the SVG content
  // fitTo 'width' mode maintains aspect ratio while targeting the specified width
  const resvg = new Resvg(svg, {
    fitTo: {
      mode: 'width',
      value: options.width,
    },
    // Optional: configure background (default is transparent)
    // background: 'white',
  })

  // Render to PNG
  const pngData = resvg.render()
  const png = pngData.asPng()

  const renderTime = performance.now() - start

  return {
    png: new Uint8Array(png),
    renderTime,
    // Memory tracking could be added with process.memoryUsage() if needed
  }
}

/**
 * Batch render multiple SVGs to PNGs.
 * Useful for benchmarking throughput on multiple cards.
 */
export async function renderBatch(
  svgs: string[],
  options: RenderOptions
): Promise<{ results: RenderResult[]; totalTime: number }> {
  const start = performance.now()
  const results: RenderResult[] = []

  for (const svg of svgs) {
    const result = await renderSvgToPng(svg, options)
    results.push(result)
  }

  return {
    results,
    totalTime: performance.now() - start,
  }
}

/**
 * Alternative renderer using 'original' fit mode (no scaling).
 * Useful for comparing performance with/without scaling.
 */
export async function renderSvgToPngOriginalSize(
  svg: string
): Promise<RenderResult> {
  const start = performance.now()

  const resvg = new Resvg(svg, {
    fitTo: {
      mode: 'original',
    },
  })

  const pngData = resvg.render()
  const png = pngData.asPng()

  return {
    png: new Uint8Array(png),
    renderTime: performance.now() - start,
  }
}

// Re-export for convenience
export { Resvg }
